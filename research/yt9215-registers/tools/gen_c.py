"""C register header."""
from model import (all_fields, elems, fsym, n_elems, packed, plain, values_of)

P = "YT921X_"


def c_addr(reg):
    if not reg["dims"]:
        return "UINT32_C(0x%05x)" % reg["address"]
    s = "(UINT32_C(0x%05x)" % reg["address"]
    for d in reg["dims"]:
        v = "(uint32_t)(%s)" % d["var"]
        if d["first"]:
            v = "((uint32_t)(%s) - %du)" % (d["var"], d["first"])
        if d["stride"] < 0:
            s += " - %du * %s" % (-d["stride"], v)
        else:
            s += " + %du * %s" % (d["stride"], v)
    return s + ")"


def c_shift(a, base=0):
    """C expression for the bit position of an array element inside its word."""
    s = str(a["lsb"] - base) if a["lsb"] - base else ""
    for d in a["dims"]:
        v = "(%s)" % d["var"] if not d["first"] else "((%s) - %d)" % (d["var"], d["first"])
        t = v if abs(d["step"]) == 1 else "%d * %s" % (abs(d["step"]), v)
        if d["step"] < 0:
            s += " - " + t
        else:
            s += (" + " if s else "") + t
    return "(%s)" % s


def generate(m):
    o = []
    w = o.append
    w("/* SPDX-License-Identifier: Apache-2.0 */")
    w("/*")
    w(" * %s register definitions." % m.d["device"]["title"])
    w(" *")
    w(" * Generated by tools/generate.py from yt921x.yaml. Do not edit.")
    w(" *")
    w(" * Naming: YT921X_<REGISTER> is a register address, with index arguments")
    w(" * where the register is an array. YT921X_<REGISTER>_<FIELD>_M is a field")
    w(" * mask inside its 32-bit word and ..._S its shift. Fields of registers")
    w(" * wider than 32 bits also have ..._W (word index), ..._LSB and ..._WIDTH")
    w(" * (position in the whole register). Array fields take the index as an")
    w(" * argument: ..._M(port). Enumerated values are plain numbers that have to")
    w(" * be shifted into place with YT921X_FPREP().")
    w(" */")
    w("#ifndef YT921X_REGS_H")
    w("#define YT921X_REGS_H")
    w("")
    w("#include <stdint.h>")
    w("")
    w("#ifdef __cplusplus")
    w('extern "C" {')
    w("#endif")
    w("")
    w("/** Mask of @p width bits starting at bit @p lsb of a 32-bit word. */")
    w("#define YT921X_MASK(lsb, width) \\")
    w("\t((uint32_t)((UINT64_C(1) << (width)) - 1u) << (lsb))")
    w("/** Extract field F (a name without the _M or _S suffix) from a register value. */")
    w("#define YT921X_FGET(val, F) (((uint32_t)(val) & F##_M) >> F##_S)")
    w("/** Shift a value into the position of field F. */")
    w("#define YT921X_FPREP(F, x) (((uint32_t)(x) << F##_S) & F##_M)")
    w("/** Extract element i of array field F from a register value. */")
    w("#define YT921X_FGET_AT(val, F, i) (((uint32_t)(val) & F##_M(i)) >> F##_S(i))")
    w("/** Shift a value into the position of element i of array field F. */")
    w("#define YT921X_FPREP_AT(F, i, x) (((uint32_t)(x) << F##_S(i)) & F##_M(i))")
    w("")
    w("/** Read a field of up to 64 bits from a register held as 32-bit words. */")
    w("static inline uint64_t yt921x_bits_get(const uint32_t *words, unsigned int lsb,")
    w("\t\t\t\t      unsigned int width)")
    w("{")
    w("\tuint64_t v = 0;")
    w("")
    w("\tfor (unsigned int i = 0; i < width; i++) {")
    w("\t\tunsigned int b = lsb + i;")
    w("")
    w("\t\tv |= (uint64_t)((words[b / 32u] >> (b % 32u)) & 1u) << i;")
    w("\t}")
    w("\treturn v;")
    w("}")
    w("")
    w("/** Write a field of up to 64 bits into a register held as 32-bit words. */")
    w("static inline void yt921x_bits_set(uint32_t *words, unsigned int lsb,")
    w("\t\t\t\t   unsigned int width, uint64_t value)")
    w("{")
    w("\tfor (unsigned int i = 0; i < width; i++) {")
    w("\t\tunsigned int b = lsb + i;")
    w("\t\tuint32_t bit = UINT32_C(1) << (b % 32u);")
    w("")
    w("\t\tif ((value >> i) & 1u)")
    w("\t\t\twords[b / 32u] |= bit;")
    w("\t\telse")
    w("\t\t\twords[b / 32u] &= ~bit;")
    w("\t}")
    w("}")
    w("")
    w("/* ---- Constants ---- */")
    for c in m.constants:
        w("/** %s. */" % plain(c["desc"]))
        w("#define %s%s %d" % (P, c["name"], c["value"]))
    w("")
    w("/* ---- Shared enumerations ---- */")
    for e in m.d["enums"]:
        w("/* %s */" % e["title"])
        for v in e["values"]:
            w("#define %s%s_%s %du" % (P, e["name"].upper(), v["name"], v["value"]))
    for blk in m.blocks:
        w("")
        w("/* ==== %s ==== */" % blk["title"])
        for reg in m.block_regs(blk["id"]):
            w("")
            rng = ", ".join("%s = %d..%d" % (d["var"], d["first"], d["first"] + d["count"] - 1)
                            for d in reg["dims"])
            w("/** %s%s%s */" % (reg["title"], ". " if rng else "", rng))
            sym = P + reg["id"]
            if reg["dims"]:
                w("#define %s(%s) \\\n\t%s" % (sym, ", ".join(d["var"] for d in reg["dims"]),
                                              c_addr(reg)))
                for d in reg["dims"]:
                    w("#define %s_%s_FIRST %du" % (sym, d["var"].upper(), d["first"]))
                    w("#define %s_%s_COUNT %du" % (sym, d["var"].upper(), d["count"]))
            else:
                w("#define %s %s" % (sym, c_addr(reg)))
            multi = reg["words"] > 1
            if multi:
                w("#define %s_WORDS %du" % (sym, reg["words"]))
            if "reset" in reg:
                w("#define %s_RESET UINT32_C(0x%08x)" % (sym, reg["reset"]))
            last_lay = None
            for lay, f in all_fields(reg):
                if lay is not last_lay:
                    w("/* %s layout: %s */" % (lay["name"], lay["title"]))
                    last_lay = lay
                fs = P + fsym(reg, f, lay)
                word = f["lsb"] // 32
                one_word = (f["lsb"] + f["width"] - 1) // 32 == word
                base = 32 * word
                a = f.get("array")
                if a:
                    args = ", ".join(d["var"] for d in a["dims"])
                    w("#define %s_S(%s) %s" % (fs, args, c_shift(a, base)))
                    w("#define %s_M(%s) (UINT32_C(0x%x) << %s_S(%s))"
                      % (fs, args, (1 << a["width"]) - 1, fs, args))
                    for d in a["dims"]:
                        if len(a["dims"]) == 1:
                            w("#define %s_COUNT %du" % (fs, d["count"]))
                        else:
                            w("#define %s_%s_COUNT %du" % (fs, d["var"].upper(), d["count"]))
                    if packed(f):
                        w("#define %s_ALL_M UINT32_C(0x%08x)"
                          % (fs, ((1 << f["width"]) - 1) << (f["lsb"] - base)))
                        w("#define %s_ALL_S %du" % (fs, f["lsb"] - base))
                elif one_word:
                    w("#define %s_M UINT32_C(0x%08x)"
                      % (fs, ((1 << f["width"]) - 1) << (f["lsb"] - base)))
                    w("#define %s_S %du" % (fs, f["lsb"] - base))
                if multi:
                    if one_word:
                        w("#define %s_W %du" % (fs, word))
                    w("#define %s_LSB %du" % (fs, f["lsb"]))
                    w("#define %s_WIDTH %du" % (fs, f["width"]))
                if "reset" in f:
                    w("#define %s_RESET %du" % (fs, f["reset"]))
                for v in f.get("values", []):
                    w("#define %s_%s %du" % (fs, v["name"], v["value"]))
    w("")
    w("/**")
    w(" * Every part the identification sequence can tell apart, as an X-macro:")
    w(" * X(name, major, mode, extmode, phy_ports, xmii_ports, serdes_ports).")
    w(" * The three port arguments are masks with one bit per port.")
    w(" */")
    w("#define YT921X_PART_TABLE(X) " + chr(92))
    for i, c in enumerate(m.chips):
        w(chr(9) + 'X("%s", 0x%04x, %d, %d, 0x%03x, 0x%03x, 0x%03x)%s' % (
            c["name"], c["major"], c["mode"], c["extmode"],
            sum(1 << p for p in c["phy"]), sum(1 << p for p in c["xmii"]),
            sum(1 << p for p in c["serdes"]),
            " " + chr(92) if i < len(m.chips) - 1 else ""))
    w("")
    w("/* ==== Port counter offsets inside MIB_DATA(port) ==== */")
    for c in m.counters:
        w("/** %s (%d bits). */" % (plain(c["desc"]), 32 * c["words"]))
        w("#define %sMIB_%s 0x%02xu" % (P, c["name"], c["offset"]))
    w("")
    w("#ifdef __cplusplus")
    w("}")
    w("#endif")
    w("")
    w("#endif /* YT921X_REGS_H */")
    return "\n".join(o) + "\n"

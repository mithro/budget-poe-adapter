"""MicroPython / Python register module."""
from model import all_fields, fsym, packed, plain
from gen_rust import r_addr, r_lsb


def generate(m):
    o = []
    w = o.append
    w("# SPDX-License-Identifier: Apache-2.0")
    w('"""%s register definitions.' % m.d["device"]["title"])
    w("")
    w("Generated by tools/generate.py from yt921x.yaml. Do not edit.")
    w("")
    w("A register is an address constant, or a function taking the index when the")
    w("register is an array. REG_FIELD_M is a field mask inside its 32-bit word and")
    w("REG_FIELD_S its shift. Fields of registers wider than 32 bits also have")
    w("REG_FIELD_W (word index), REG_FIELD_LSB and REG_FIELD_WIDTH. Array fields")
    w("are functions taking the index: REG_FIELD_M(port). Enumerated values are")
    w('plain numbers named REG_FIELD_VALUE."""')
    w("")
    w("try:")
    w("    from micropython import const")
    w("except ImportError:  # CPython")
    w("    def const(x):")
    w("        return x")
    w("")
    w("")
    w("def fget(val, mask, shift):")
    w('    """Extract a field from a register value."""')
    w("    return (val & mask) >> shift")
    w("")
    w("")
    w("def fprep(mask, shift, x):")
    w('    """Shift a value into the position of a field."""')
    w("    return (x << shift) & mask")
    w("")
    w("")
    w("def bits_get(words, lsb, width):")
    w('    """Read a field from a register held as a list of 32-bit words."""')
    w("    v = 0")
    w("    for i, word in enumerate(words):")
    w("        v |= word << (32 * i)")
    w("    return (v >> lsb) & ((1 << width) - 1)")
    w("")
    w("")
    w("def bits_set(words, lsb, width, value):")
    w('    """Write a field into a register held as a list of 32-bit words."""')
    w("    mask = ((1 << width) - 1) << lsb")
    w("    v = 0")
    w("    for i, word in enumerate(words):")
    w("        v |= word << (32 * i)")
    w("    v = (v & ~mask) | ((value << lsb) & mask)")
    w("    for i in range(len(words)):")
    w("        words[i] = (v >> (32 * i)) & 0xFFFFFFFF")
    w("")
    w("")
    w("# ---- Constants ----")
    for c in m.constants:
        w("%s = const(%d)  # %s" % (c["name"], c["value"], plain(c["desc"])))
    w("")
    w("# ---- Shared enumerations ----")
    for e in m.d["enums"]:
        w("# %s" % e["title"])
        for v in e["values"]:
            w("%s_%s = const(%d)" % (e["name"].upper(), v["name"], v["value"]))
    for blk in m.blocks:
        w("")
        w("# ==== %s ====" % blk["title"])
        for reg in m.block_regs(blk["id"]):
            w("")
            rid = reg["id"]
            rng = ", ".join("%s = %d..%d" % (d["var"], d["first"], d["first"] + d["count"] - 1)
                            for d in reg["dims"])
            w("# %s%s%s" % (reg["title"], ". " if rng else "", rng))
            if reg["dims"]:
                w("def %s(%s):" % (rid, ", ".join(d["var"] for d in reg["dims"])))
                w("    return %s" % r_addr(reg))
                w("")
                w("")
                for d in reg["dims"]:
                    w("%s_%s_FIRST = const(%d)" % (rid, d["var"].upper(), d["first"]))
                    w("%s_%s_COUNT = const(%d)" % (rid, d["var"].upper(), d["count"]))
            else:
                w("%s = const(0x%05x)" % (rid, reg["address"]))
            multi = reg["words"] > 1
            if multi:
                w("%s_WORDS = const(%d)" % (rid, reg["words"]))
            if "reset" in reg:
                w("%s_RESET = const(0x%08x)" % (rid, reg["reset"]))
            pending_blank = False
            for lay, f in all_fields(reg):
                fs = fsym(reg, f, lay)
                word = f["lsb"] // 32
                one_word = (f["lsb"] + f["width"] - 1) // 32 == word
                base = 32 * word
                a = f.get("array")
                if a:
                    args = ", ".join(d["var"] for d in a["dims"])
                    sh = dict(a, lsb=a["lsb"] - base)
                    w("")
                    w("")
                    w("def %s_S(%s):" % (fs, args))
                    w("    return %s" % r_lsb(sh))
                    w("")
                    w("")
                    w("def %s_M(%s):" % (fs, args))
                    w("    return 0x%x << (%s)" % ((1 << a["width"]) - 1, r_lsb(sh)))
                    w("")
                    w("")
                    if packed(f):
                        w("%s_ALL_M = const(0x%08x)" % (fs, ((1 << f["width"]) - 1) << (f["lsb"] - base)))
                        w("%s_ALL_S = const(%d)" % (fs, f["lsb"] - base))
                elif one_word:
                    w("%s_M = const(0x%08x)" % (fs, ((1 << f["width"]) - 1) << (f["lsb"] - base)))
                    w("%s_S = const(%d)" % (fs, f["lsb"] - base))
                if multi:
                    if one_word:
                        w("%s_W = const(%d)" % (fs, word))
                    w("%s_LSB = const(%d)" % (fs, f["lsb"]))
                    w("%s_WIDTH = const(%d)" % (fs, f["width"]))
                if "reset" in f:
                    w("%s_RESET = const(%d)" % (fs, f["reset"]))
                for v in f.get("values", []):
                    w("%s_%s = const(%d)" % (fs, v["name"], v["value"]))
    w("")
    w("# Every part the identification sequence can tell apart:")
    w("# (name, major, mode, extmode, phy_ports, xmii_ports, serdes_ports).")
    w("# The three port entries are masks with one bit per port.")
    w("PARTS = (")
    for c in m.chips:
        w('    ("%s", 0x%04x, %d, %d, 0x%03x, 0x%03x, 0x%03x),' % (
            c["name"], c["major"], c["mode"], c["extmode"],
            sum(1 << p for p in c["phy"]), sum(1 << p for p in c["xmii"]),
            sum(1 << p for p in c["serdes"])))
    w(")")
    w("")
    w("# ==== Port counter offsets inside MIB_DATA(port) ====")
    for c in m.counters:
        w("MIB_%s = const(0x%02x)  # %s (%d bits)" % (c["name"], c["offset"],
                                                    plain(c["desc"]), 32 * c["words"]))
    text = "\n".join(o) + "\n"
    # PEP 8: two blank lines around functions, never more
    import re
    text = re.sub(r"\n{4,}", "\n\n\n", text)
    return text

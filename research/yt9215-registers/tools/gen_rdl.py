"""SystemRDL description, one file per chip family."""
from gen_svd import is_packed
from model import elems, lowest_addr, n_elems, plain, values_of, visible_fields


def q(text):
    return '"' + plain(text).replace("\\", "\\\\").replace('"', '\\"') + '"'


def emit_fields(o, m, reg, fields, family, ind, width, ename):
    used = set()
    enums = []
    lines = []
    for f in sorted(fields, key=lambda f: -f["lsb"]):
        sw = "r" if f["access"] == "ro" else "rw"
        hw = "w" if f["access"] == "ro" else "r"
        a = f.get("array")
        parts = []
        if a:
            for idx, lsb, w in elems(f):
                parts.append((f["name"] + "".join("_%d" % i for i in idx), lsb, w))
        else:
            parts.append((f["name"], f["lsb"], f["width"]))
        vals = [v for v in values_of(m, f) if not v.get("chip") or v["chip"] == family]
        w0 = parts[0][2]
        vals = [v for v in vals if v["value"] < (1 << w0)]
        enc = ""
        if vals:
            en = "%s_%s_e" % (ename, f["name"].lower())
            if en not in used:
                used.add(en)
                enums.append("%senum %s {" % (ind, en))
                for v in vals:
                    enums.append("%s    %s = %d { desc = %s; };" % (ind, v["name"], v["value"],
                                                                 q(v["desc"])))
                enums.append("%s};" % ind)
            enc = " encode = %s;" % en
        for name, lsb, w in sorted(parts, key=lambda p: -p[1]):
            lines.append("%sfield { desc = %s; sw = %s; hw = %s;%s } %s[%d:%d];"
                         % (ind, q(f["desc"]), sw, hw, enc, name, lsb + w - 1, lsb))
    o.extend(enums)
    o.extend(lines)


def reg_body(o, m, reg, family, ind, lay=None):
    width = {1: 32, 2: 64, 3: 128}[reg["words"]]
    name = reg["title"] if lay is None else "%s, %s layout" % (reg["title"], lay["name"])
    o.append("%sname = %s;" % (ind, q(name)))
    desc = reg["desc"]
    if lay is not None:
        desc = "Layout for key types %s: %s. %s" % (", ".join(lay["types"]), lay["title"], desc)
    if reg["dims"]:
        desc += " Index: " + ", ".join(
            "%s = %d to %d" % (d["var"], d["first"], d["first"] + d["count"] - 1)
            for d in reg["dims"]) + "."
    o.append("%sdesc = %s;" % (ind, q(desc)))
    if width != 32:
        o.append("%sregwidth = %d;" % (ind, width))
    fields = visible_fields(reg, family)
    if lay is not None:
        fields = fields + visible_fields(reg, family, lay)
    ename = reg["id"].lower() + ("_" + lay["name"].lower() if lay is not None else "")
    emit_fields(o, m, reg, fields, family, ind, width, ename)
    if lay is None and reg["layouts"]:
        # SystemRDL has no alternate layouts: describe the bits whose meaning
        # depends on the key type as opaque fields.
        taken = set()
        for f in fields:
            taken.update(range(f["lsb"], f["lsb"] + f["width"]))
        bits = set()
        for l in reg["layouts"]:
            for f in l["fields"]:
                bits.update(range(f["lsb"], f["lsb"] + f["width"]))
        bits -= taken
        runs = []
        for b in sorted(bits):
            if runs and runs[-1][1] == b - 1:
                runs[-1][1] = b
            else:
                runs.append([b, b])
        for lo, hi in reversed(runs):
            o.append('%sfield { desc = "Meaning depends on the key type; see the ACL key '
                     'layouts in the documentation."; sw = rw; hw = r; } LAYOUT_%d[%d:%d];'
                     % (ind, lo, hi, lo))


def generate(m, family):
    dev = m.d["device"]
    parts = [c["name"] for c in m.chips if c["family"] == family]
    o = []
    o.append("// Generated by tools/generate.py from yt921x.yaml. Do not edit.")
    o.append("//")
    o.append("// SystemRDL 2.0. Registers wider than 32 bits are read and written as")
    o.append("// 32-bit words, low word at the lower address. The addresses are those")
    o.append("// of the switch register space, reached indirectly over MDIO.")
    o.append("")
    o.append("addrmap %s {" % family)
    o.append("    name = %s;" % q("%s, %s family" % (dev["title"], family.upper())))
    o.append("    desc = %s;" % q("Parts: " + ", ".join(parts) + "."))
    o.append("    default regwidth = 32;")
    o.append("    default accesswidth = 32;")
    o.append("    addressing = regalign;")
    o.append("    lsb0;")
    for r in sorted(m.regs, key=lowest_addr):
        rid = r["id"]
        dims = r["dims"]
        size = 4 * {1: 1, 2: 2, 3: 4}[r["words"]]
        o.append("")
        if rid == "MIB_DATA":
            o.append("    regfile {")
            o.append("        name = %s;" % q(r["title"]))
            o.append("        desc = %s;" % q(r["desc"]))
            for c in m.counters:
                o.append("        reg {")
                o.append("            desc = %s;" % q(c["desc"]))
                if c["words"] == 2:
                    o.append("            regwidth = 64;")
                o.append("            field { desc = %s; sw = r; hw = w; } COUNT[%d:0];"
                         % (q(c["desc"]), 32 * c["words"] - 1))
                o.append("        } %s @ 0x%02X;" % (c["name"], c["offset"]))
            o.append("    } MIB[%d] @ 0x%X += 0x%X;" % (dims[0]["count"], r["address"],
                                                    dims[0]["stride"]))
            continue
        variants = [None] + r["layouts"]
        if dims and not (is_packed(r) or len(dims) == 1):
            inner, outer = dims
            o.append("    regfile {")
            o.append("        name = %s;" % q("%s, one value of index %s" % (r["title"],
                                                                         outer["var"])))
            for lay in variants[:1]:
                o.append("        reg {")
                reg_body(o, m, r, family, "            ")
                o.append("        } %s[%d] @ 0x0 += 0x%X;" % (inner["var"].upper(),
                                                           inner["count"], inner["stride"]))
            o.append("    } %s[%d] @ 0x%X += 0x%X;" % (rid, outer["count"], lowest_addr(r),
                                                    outer["stride"]))
            continue
        o.append("    reg {")
        reg_body(o, m, r, family, "        ")
        if not dims:
            o.append("    } %s @ 0x%X;" % (rid, r["address"]))
        else:
            stride = abs(dims[-1]["stride"]) if is_packed(r) else dims[0]["stride"]
            if len(dims) > 1 and all(d["stride"] > 0 for d in dims):
                arr = "".join("[%d]" % d["count"] for d in dims)
            else:
                arr = "[%d]" % n_elems(r)
            o.append("    } %s%s @ 0x%X += 0x%X;" % (rid, arr, lowest_addr(r), stride))
    o.append("};")
    return "\n".join(o) + "\n"

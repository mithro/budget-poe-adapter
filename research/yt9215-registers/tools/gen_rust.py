"""Rust register module (no_std)."""
from model import all_fields, fsym, packed, plain


def r_addr(reg):
    s = "0x%05x" % reg["address"]
    for d in reg["dims"]:
        v = d["var"] if not d["first"] else "(%s - %d)" % (d["var"], d["first"])
        if d["stride"] < 0:
            s += " - %d * %s" % (-d["stride"], v)
        else:
            s += " + %d * %s" % (d["stride"], v)
    return s


def r_lsb(a):
    s = str(a["lsb"]) if a["lsb"] else ""
    for d in a["dims"]:
        v = d["var"] if not d["first"] else "(%s - %d)" % (d["var"], d["first"])
        t = v if abs(d["step"]) == 1 else "%d * %s" % (abs(d["step"]), v)
        if d["step"] < 0:
            s += " - " + t
        else:
            s += (" + " if s else "") + t
    return s


def generate(m):
    o = []
    w = o.append
    w("// SPDX-License-Identifier: Apache-2.0")
    w("//! %s register definitions." % m.d["device"]["title"])
    w("//!")
    w("//! Generated by `tools/generate.py` from `yt921x.yaml`. Do not edit.")
    w("//!")
    w("//! A register is a `u32` address constant, or a `const fn` taking the index")
    w("//! when the register is an array. A field is a [`Field`] constant named")
    w("//! `<REGISTER>_<FIELD>`, or a `const fn` taking the index for array fields.")
    w("//! Enumerated values are plain `u32` constants named")
    w("//! `<REGISTER>_<FIELD>_<VALUE>`.")
    w("")
    w("/// Position of a bit field inside a register of one or more 32-bit words.")
    w("#[derive(Clone, Copy, Debug, PartialEq, Eq)]")
    w("pub struct Field {")
    w("    /// Lowest bit of the field, counted from bit 0 of the first word.")
    w("    pub lsb: u8,")
    w("    /// Number of bits.")
    w("    pub width: u8,")
    w("}")
    w("")
    w("impl Field {")
    w("    /// Index of the 32-bit word that holds the lowest bit.")
    w("    pub const fn word(self) -> usize {")
    w("        (self.lsb / 32) as usize")
    w("    }")
    w("")
    w("    /// Shift of the field inside its word.")
    w("    pub const fn shift(self) -> u32 {")
    w("        (self.lsb % 32) as u32")
    w("    }")
    w("")
    w("    /// Mask of the field inside its word. Bits that fall into the next")
    w("    /// word are cut off; use [`Field::get_words`] for such fields.")
    w("    pub const fn mask(self) -> u32 {")
    w("        ((((1u64 << self.width) - 1) << self.shift()) & 0xffff_ffff) as u32")
    w("    }")
    w("")
    w("    /// Extract the field from the value of its word.")
    w("    pub const fn get(self, word: u32) -> u32 {")
    w("        (word & self.mask()) >> self.shift()")
    w("    }")
    w("")
    w("    /// Shift a value into the position of the field inside its word.")
    w("    pub const fn prep(self, value: u32) -> u32 {")
    w("        (value << self.shift()) & self.mask()")
    w("    }")
    w("")
    w("    /// Replace the field in the value of its word.")
    w("    pub const fn set(self, word: u32, value: u32) -> u32 {")
    w("        (word & !self.mask()) | self.prep(value)")
    w("    }")
    w("")
    w("    /// Extract a field of up to 64 bits from a register held as words.")
    w("    pub fn get_words(self, words: &[u32]) -> u64 {")
    w("        let mut v = 0u64;")
    w("        for i in 0..self.width as usize {")
    w("            let b = self.lsb as usize + i;")
    w("            v |= (((words[b / 32] >> (b % 32)) & 1) as u64) << i;")
    w("        }")
    w("        v")
    w("    }")
    w("")
    w("    /// Write a field of up to 64 bits into a register held as words.")
    w("    pub fn set_words(self, words: &mut [u32], value: u64) {")
    w("        for i in 0..self.width as usize {")
    w("            let b = self.lsb as usize + i;")
    w("            let bit = 1u32 << (b % 32);")
    w("            if (value >> i) & 1 != 0 {")
    w("                words[b / 32] |= bit;")
    w("            } else {")
    w("                words[b / 32] &= !bit;")
    w("            }")
    w("        }")
    w("    }")
    w("}")
    w("")
    w("// ---- Constants ----")
    for c in m.constants:
        w("/// %s." % plain(c["desc"]))
        w("pub const %s: i32 = %d;" % (c["name"], c["value"]))
    w("")
    w("// ---- Shared enumerations ----")
    for e in m.d["enums"]:
        for v in e["values"]:
            w("/// %s: %s." % (e["title"], plain(v["desc"]).rstrip(".")))
            w("pub const %s_%s: u32 = %d;" % (e["name"].upper(), v["name"], v["value"]))
    for blk in m.blocks:
        w("")
        w("// ==== %s ====" % blk["title"])
        for reg in m.block_regs(blk["id"]):
            w("")
            rid = reg["id"]
            if reg["dims"]:
                rng = ", ".join("`%s` = %d..=%d" % (d["var"], d["first"],
                                                   d["first"] + d["count"] - 1)
                                for d in reg["dims"])
                w("/// %s. %s." % (reg["title"], rng))
                w("pub const fn %s(%s) -> u32 {" % (
                    rid.lower(), ", ".join("%s: u32" % d["var"] for d in reg["dims"])))
                w("    %s" % r_addr(reg))
                w("}")
                for d in reg["dims"]:
                    w("/// First valid `%s` of [`%s`]." % (d["var"], rid.lower()))
                    w("pub const %s_%s_FIRST: u32 = %d;" % (rid, d["var"].upper(), d["first"]))
                    w("/// Number of valid `%s` values of [`%s`]." % (d["var"], rid.lower()))
                    w("pub const %s_%s_COUNT: u32 = %d;" % (rid, d["var"].upper(), d["count"]))
            else:
                w("/// %s." % reg["title"])
                w("pub const %s: u32 = 0x%05x;" % (rid, reg["address"]))
            if reg["words"] > 1:
                w("/// Number of 32-bit words of one %s entry." % rid)
                w("pub const %s_WORDS: usize = %d;" % (rid, reg["words"]))
            if "reset" in reg:
                w("/// Reset value of %s." % rid)
                w("pub const %s_RESET: u32 = 0x%08x;" % (rid, reg["reset"]))
            for lay, f in all_fields(reg):
                fs = fsym(reg, f, lay)
                doc = plain(f["desc"]) or f["name"]
                a = f.get("array")
                if a:
                    w("/// %s" % doc)
                    w("pub const fn %s(%s) -> Field {" % (
                        fs.lower(), ", ".join("%s: u32" % d["var"] for d in a["dims"])))
                    w("    Field { lsb: (%s) as u8, width: %d }" % (r_lsb(a), a["width"]))
                    w("}")
                    if packed(f):
                        w("/// All elements of [`%s`] as one field." % fs.lower())
                        w("pub const %s_ALL: Field = Field { lsb: %d, width: %d };"
                          % (fs, f["lsb"], f["width"]))
                else:
                    w("/// %s" % doc)
                    w("pub const %s: Field = Field { lsb: %d, width: %d };"
                      % (fs, f["lsb"], f["width"]))
                if "reset" in f:
                    w("/// Reset value of %s." % fs)
                    w("pub const %s_RESET: u32 = %d;" % (fs, f["reset"]))
                for v in f.get("values", []):
                    w("/// %s" % (plain(v["desc"]) or v["name"]))
                    w("pub const %s_%s: u32 = %d;" % (fs, v["name"], v["value"]))
    w("")
    w("/// One part of the family and how to recognise it.")
    w("#[derive(Clone, Copy, Debug, PartialEq, Eq)]")
    w("pub struct Part {")
    w("    /// Part number.")
    w("    pub name: &'static str,")
    w("    /// Expected CHIP_ID.MAJOR.")
    w("    pub major: u16,")
    w("    /// Expected CHIP_MODE.MODE.")
    w("    pub mode: u8,")
    w("    /// Expected extended mode byte of the configuration byte store.")
    w("    pub extmode: u8,")
    w("    /// Ports with a built-in PHY, one bit per port.")
    w("    pub phy_ports: u16,")
    w("    /// Ports with xMII pins, one bit per port.")
    w("    pub xmii_ports: u16,")
    w("    /// Ports with a SerDes, one bit per port.")
    w("    pub serdes_ports: u16,")
    w("}")
    w("")
    w("/// Every part the identification sequence can tell apart.")
    w("pub const PARTS: [Part; %d] = [" % len(m.chips))
    for c in m.chips:
        w("    Part {")
        w('        name: "%s",' % c["name"])
        w("        major: 0x%04x," % c["major"])
        w("        mode: %d," % c["mode"])
        w("        extmode: %d," % c["extmode"])
        w("        phy_ports: 0x%03x," % sum(1 << p for p in c["phy"]))
        w("        xmii_ports: 0x%03x," % sum(1 << p for p in c["xmii"]))
        w("        serdes_ports: 0x%03x," % sum(1 << p for p in c["serdes"]))
        w("    },")
    w("];")
    w("")
    w("// ==== Port counter offsets inside mib_data(port) ====")
    for c in m.counters:
        w("/// %s (%d bits)." % (plain(c["desc"]), 32 * c["words"]))
        w("pub const MIB_%s: u32 = 0x%02x;" % (c["name"], c["offset"]))
    return "\n".join(o) + "\n"
